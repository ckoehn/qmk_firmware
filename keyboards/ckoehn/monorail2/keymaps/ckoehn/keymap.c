void keyboard_pre_init_user(void) {
    setPinOutput(LED0_PIN);
    setPinOutput(LED1_PIN);
    setPinOutput(LED2_PIN);
}

layer_state_t layer_state_set_user(layer_state_t state) {
    switch (get_highest_layer(state)) {
    case _GAME:
        writePin(LED0_PIN, 1);
        writePin(LED1_PIN, 1);
        writePin(LED2_PIN, 1);
        break;
    default:
        writePin(LED0_PIN, 0);
        writePin(LED1_PIN, 0);
        writePin(LED2_PIN, 0);
        break;
    }
    return state;
}
